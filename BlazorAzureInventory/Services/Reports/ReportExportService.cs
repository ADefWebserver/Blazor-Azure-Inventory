using System.Globalization;
using System.Text;
using BlazorAzureInventory.Components.Inventory;
using BlazorAzureInventory.Models.Graph;
using BlazorAzureInventory.Models.Inventory;
using BlazorAzureInventory.Models.Options;
using BlazorAzureInventory.Models.Users;
using BlazorAzureInventory.Services.Graph;
using ClosedXML.Excel;
using Microsoft.Extensions.Options;

namespace BlazorAzureInventory.Services.Reports;

/// <summary>A sheet or CSV file: a name, column headers, and rows of plain values.</summary>
public sealed record ReportTable(string Name, IReadOnlyList<string> Headers, IReadOnlyList<IReadOnlyList<object?>> Rows);

/// <summary>Builds downloadable Excel and CSV reports from the in-memory scan. Never calls Azure.</summary>
public sealed class ReportExportService(IOptions<QuotaOptions> quotaOptions)
{
    public const string ExcelContentType = "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet";
    public const string CsvContentType = "text/csv";

    private static readonly HashSet<string> ConnectionEdges = new(StringComparer.Ordinal) { EdgeTypes.ConnectsTo, EdgeTypes.ReferencesSecret, EdgeTypes.PullsImageFrom };

    private int MaxRows => quotaOptions.Value.Reports.MaxRows;

    public static readonly IReadOnlyList<string> InventoryTables = ["Web & Function Apps", "SQL", "Storage", "Container Apps", "Registries", "Other"];

    public IReadOnlyList<ReportTable> BuildTables(InventorySnapshot snapshot, GraphIndex? index, SnapshotDiff? changes)
    {
        var view = InventoryView.Build(snapshot, index);
        var tables = new List<ReportTable>
        {
            Apps(view), Sql(view), Storage(view), ContainerApps(view), Simple("Registries", view.Registries), Simple("Other", view.Other)
        };
        if (index is not null) tables.Add(Connections(index));
        tables.Add(Tags(snapshot));
        tables.Add(Issues(snapshot));
        if (changes is not null) tables.Add(Changes(changes));
        return tables;
    }

    public MemoryStream BuildInventoryWorkbook(InventorySnapshot snapshot, GraphIndex? index, SnapshotDiff? changes, string generatedBy)
    {
        var tables = BuildTables(snapshot, index, changes);
        using var workbook = new XLWorkbook();
        var truncated = new List<string>();
        var summary = workbook.Worksheets.Add("Summary");
        var rows = new List<(string, object?)>
        {
            ("Report", "Azure Inventory"),
            ("Data as of (UTC)", snapshot.ScannedUtc.UtcDateTime.ToString("yyyy-MM-dd HH:mm", CultureInfo.InvariantCulture)),
            ("Generated (UTC)", DateTime.UtcNow.ToString("yyyy-MM-dd HH:mm", CultureInfo.InvariantCulture)),
            ("Generated by", generatedBy),
            ("Tenants", string.Join(", ", snapshot.Tenants.Select(t => t.DisplayName))),
            ("Subscriptions", string.Join(", ", snapshot.Subscriptions.Select(s => s.DisplayName))),
            ("Resources", snapshot.Resources.Count),
            ("Scan issues", snapshot.Issues.Count)
        };
        foreach (var group in snapshot.Resources.GroupBy(r => r.Kind).OrderBy(g => g.Key.ToString()))
        {
            rows.Add(($"  {group.Key}", group.Count()));
        }
        if (changes is not null) rows.Add(("Changes since previous scan", changes.TotalCount));

        foreach (var table in tables)
        {
            if (WriteSheet(workbook, table)) truncated.Add(table.Name);
        }
        if (truncated.Count > 0) rows.Add(("Truncated sheets", $"{string.Join(", ", truncated)} (limit {MaxRows} rows)"));

        for (var i = 0; i < rows.Count; i++)
        {
            summary.Cell(i + 1, 1).Value = rows[i].Item1;
            SetCell(summary.Cell(i + 1, 2), rows[i].Item2);
        }
        summary.Column(1).Style.Font.Bold = true;
        summary.Columns(1, 2).AdjustToContents();
        return Save(workbook);
    }

    public MemoryStream BuildUsersWorkbook(IEnumerable<UserRecord> users)
    {
        var table = new ReportTable("Users",
            ["Username", "Display name", "Role", "Status", "Bootstrap", "Last sign-in (UTC)", "Added by", "Added (UTC)"],
            users.Select(u => (IReadOnlyList<object?>)[u.Username, u.DisplayName, u.Role, u.Status.ToString(), u.IsBootstrap ? "Yes" : "No",
                u.LastSignInUtc?.UtcDateTime, u.AddedBy, u.AddedUtc.UtcDateTime]).ToList());
        using var workbook = new XLWorkbook();
        WriteSheet(workbook, table);
        return Save(workbook);
    }

    public MemoryStream BuildCsv(ReportTable table)
    {
        var sb = new StringBuilder();
        sb.AppendLine(string.Join(',', table.Headers.Select(CsvField)));
        foreach (var row in table.Rows.Take(MaxRows))
        {
            sb.AppendLine(string.Join(',', row.Select(v => CsvField(Format(v)))));
        }
        return new MemoryStream(new UTF8Encoding(encoderShouldEmitUTF8Identifier: true).GetPreamble().Concat(Encoding.UTF8.GetBytes(sb.ToString())).ToArray());
    }

    /// <summary>Prefixes values that a spreadsheet would treat as a formula, so exported data can never execute.</summary>
    public static string Sanitize(string? value)
    {
        if (string.IsNullOrEmpty(value)) return value ?? "";
        return value[0] is '=' or '+' or '-' or '@' or '\t' or '\r' ? "'" + value : value;
    }

    private bool WriteSheet(XLWorkbook workbook, ReportTable table)
    {
        var sheet = workbook.Worksheets.Add(SheetName(table.Name));
        for (var c = 0; c < table.Headers.Count; c++) sheet.Cell(1, c + 1).Value = table.Headers[c];
        var count = Math.Min(table.Rows.Count, MaxRows);
        for (var r = 0; r < count; r++)
        {
            var row = table.Rows[r];
            for (var c = 0; c < row.Count; c++) SetCell(sheet.Cell(r + 2, c + 1), row[c]);
        }
        if (table.Headers.Count > 0)
        {
            var range = sheet.Range(1, 1, Math.Max(1, count + 1), table.Headers.Count);
            if (count > 0) range.CreateTable(TableName(table.Name));
            else sheet.Row(1).Style.Font.Bold = true;
            sheet.SheetView.FreezeRows(1);
            sheet.Columns(1, table.Headers.Count).AdjustToContents(1, Math.Min(count + 1, 500), 8, 80);
        }
        return table.Rows.Count > MaxRows;
    }

    private static void SetCell(IXLCell cell, object? value)
    {
        switch (value)
        {
            case null: cell.Value = Blank.Value; break;
            case int i: cell.Value = i; break;
            case long l: cell.Value = l; break;
            case DateTime d: cell.Value = d; cell.Style.DateFormat.Format = "yyyy-mm-dd hh:mm"; break;
            // Strings are always written as text, never as formulas.
            default: cell.SetValue(Sanitize(Format(value))); break;
        }
    }

    private static string Format(object? value) => value switch
    {
        null => "",
        DateTime d => d.ToString("yyyy-MM-dd HH:mm", CultureInfo.InvariantCulture),
        IFormattable f => f.ToString(null, CultureInfo.InvariantCulture),
        _ => value.ToString() ?? ""
    };

    private static string CsvField(string value)
    {
        var safe = Sanitize(value);
        return safe.IndexOfAny([',', '"', '\n', '\r']) >= 0 ? "\"" + safe.Replace("\"", "\"\"") + "\"" : safe;
    }

    private static string TagText(AzureResourceInfo r) => string.Join("; ", r.Tags.OrderBy(t => t.Key, StringComparer.OrdinalIgnoreCase).Select(t => $"{t.Key}={t.Value}"));

    private static ReportTable Apps(InventoryView view) => new("Web & Function Apps",
        ["Name", "Kind", "Subscription", "Resource group", "Location", "State", "Default host", "App settings", "Config files", "Connections", "Tags"],
        view.Apps.SelectMany(a => a.Slots.Prepend(a)).Select(a => (IReadOnlyList<object?>)[a.Name, a.Kind, a.Subscription, a.ResourceGroup,
            a.Location, a.State, a.DefaultHost, a.SettingsStatus.ToString(), a.ConfigFilesStatus.ToString(), a.Connections, TagText(a.Resource)]).ToList());

    private static ReportTable Sql(InventoryView view) => new("SQL",
        ["Server", "Database", "FQDN", "Subscription", "Resource group", "Location", "SKU", "Status", "Consumers", "Tags"],
        view.SqlServers.SelectMany(s => s.DatabaseRows.Count == 0
            ? (IEnumerable<IReadOnlyList<object?>>)[[s.Server, null, s.Fqdn, s.Subscription, s.ResourceGroup, s.Location, null, null, null, TagText(s.Resource)]]
            : s.DatabaseRows.Select(d => (IReadOnlyList<object?>)[s.Server, d.Name, s.Fqdn, s.Subscription, s.ResourceGroup, s.Location, d.Sku, d.Status, d.Consumers, TagText(d.Resource)]))
            .ToList());

    private static ReportTable Storage(InventoryView view) => new("Storage",
        ["Account", "Container", "Kind", "SKU", "Hierarchical namespace", "Location", "Public access", "Consumers", "Tags"],
        view.Storage.SelectMany(s => s.ContainerRows.Count == 0
            ? (IEnumerable<IReadOnlyList<object?>>)[[s.Account, null, s.Kind, s.Sku, s.HnsEnabled, s.Location, null, s.Consumers, TagText(s.Resource)]]
            : s.ContainerRows.Select(c => (IReadOnlyList<object?>)[s.Account, c.Name, s.Kind, s.Sku, s.HnsEnabled, s.Location, c.PublicAccess, c.Consumers, TagText(c.Resource)]))
            .ToList());

    private static ReportTable ContainerApps(InventoryView view) => new("Container Apps",
        ["Name", "Environment", "Images", "Registry", "Env vars", "Connections", "Resource group", "Location", "Tags"],
        view.ContainerApps.Select(c => (IReadOnlyList<object?>)[c.Name, c.Environment, c.Images, c.Registry, c.EnvVarCount, c.Connections,
            c.Resource.ResourceGroup, c.Resource.Location, TagText(c.Resource)]).ToList());

    private static ReportTable Simple(string name, IEnumerable<SimpleRow> rows) => new(name,
        ["Type", "Name", "Endpoint", "SKU", "Consumers", "Resource group", "Location", "Tags"],
        rows.Select(r => (IReadOnlyList<object?>)[r.Type, r.Name, r.EndpointHost, r.Sku, r.Consumers, r.Resource.ResourceGroup, r.Resource.Location, TagText(r.Resource)]).ToList());

    private static ReportTable Connections(GraphIndex index) => new("Connections",
        ["Source", "Source type", "Target", "Target type", "Connection", "Setting key", "Source file", "Confidence"],
        index.Graph.Edges.Where(e => ConnectionEdges.Contains(e.Type)).SelectMany(e =>
        {
            var source = index.NodesById.GetValueOrDefault(e.Source);
            var target = index.NodesById.GetValueOrDefault(e.Target);
            var refs = e.Data.GetValueOrDefault("references") as IEnumerable<EdgeReference>;
            var confidence = e.Data.GetValueOrDefault("confidence")?.ToString();
            return refs?.Any() == true
                ? refs.Select(r => (IReadOnlyList<object?>)[source?.Label ?? e.Source, source?.Type, target?.Label ?? e.Target, target?.Type, e.Type, r.SettingKey, r.FileName, r.Confidence ?? confidence])
                : (IEnumerable<IReadOnlyList<object?>>)[[source?.Label ?? e.Source, source?.Type, target?.Label ?? e.Target, target?.Type, e.Type, null, null, confidence]];
        }).ToList());

    private static ReportTable Tags(InventorySnapshot snapshot) => new("Tags",
        ["Resource", "Kind", "Resource group", "Tag name", "Tag value"],
        snapshot.Resources.SelectMany(r => r.Tags.OrderBy(t => t.Key, StringComparer.OrdinalIgnoreCase)
            .Select(t => (IReadOnlyList<object?>)[r.Name, r.Kind.ToString(), r.ResourceGroup, t.Key, t.Value])).ToList());

    private static ReportTable Issues(InventorySnapshot snapshot) => new("Scan Issues",
        ["Stage", "Resource", "Kind", "Message"],
        snapshot.Issues.Select(i => (IReadOnlyList<object?>)[i.Stage, i.ResourceName, i.Kind.ToString(), i.Message]).ToList());

    public static ReportTable Changes(SnapshotDiff diff) => new("Changes",
        ["Change", "Resource", "Kind", "Details"],
        diff.Added.Select(r => (IReadOnlyList<object?>)["Added", r.Name, r.Kind.ToString(), r.Id])
            .Concat(diff.Removed.Select(r => (IReadOnlyList<object?>)["Removed", r.Name, r.Kind.ToString(), r.Id]))
            .Concat(diff.Changed.Select(c => (IReadOnlyList<object?>)["Changed", c.Name, c.Kind.ToString(), string.Join("; ", c.Changes)]))
            .Concat(diff.ConnectionsAdded.Select(c => (IReadOnlyList<object?>)["Connection added", c.SourceLabel, c.Type, c.TargetLabel]))
            .Concat(diff.ConnectionsRemoved.Select(c => (IReadOnlyList<object?>)["Connection removed", c.SourceLabel, c.Type, c.TargetLabel]))
            .ToList());

    private static string SheetName(string name)
    {
        var cleaned = new string(name.Select(c => c is '[' or ']' or ':' or '*' or '?' or '/' or '\\' ? ' ' : c).ToArray());
        return cleaned.Length <= 31 ? cleaned : cleaned[..31];
    }

    private static string TableName(string name) => "T_" + new string(name.Where(char.IsLetterOrDigit).ToArray());

    private static MemoryStream Save(XLWorkbook workbook)
    {
        var stream = new MemoryStream();
        workbook.SaveAs(stream);
        stream.Position = 0;
        return stream;
    }
}
